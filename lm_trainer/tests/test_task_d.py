def test_d01_markdown_rendering_is_safe():
    hostile = (
        "正常回复\n```python\nprint('<script>')\n```\n"
        "<script>alert(1)</script>\n<img src=x onerror=alert(1)>\n"
        "[link](javascript:alert(1))\n😀 emoji"
    )
    rendered = safe_markdown(hostile)
    assert "<script>alert(1)</script>" not in rendered
    assert "<img src=x" not in rendered
    assert "javascript:alert" not in rendered
    assert "print('<script>')" in rendered, "code blocks stay copyable"
    assert "😀" in rendered


def test_d01_markdown_neutralises_nested_and_uppercase_payloads():
    for payload in (
        "<SCRIPT>alert(1)</SCRIPT>",
        "<iframe src=javascript:alert(1)></iframe>",
        "<a href=\"data:text/html,<script>\">x</a>",
        "[x](JAVASCRIPT:alert(1))",
    ):
        rendered = safe_markdown(payload)
        lowered = rendered.lower()
        assert "<script>alert" not in lowered
        assert "javascript:alert" not in lowered


