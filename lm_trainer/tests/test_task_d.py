def _cases(path=CASES):
    payload = json.loads(Path(path).read_text(encoding="utf-8"))
    raw, manifest = validate_cases_file(payload, source="test")
    return [EvalCase.from_dict(c) for c in raw], manifest


def _provider(responder=None):
    # The canned reply must not contain a model name: the blind-review view is
    # checked for identity leaks, so a "mock:base" reply would be a false positive.
    return MockRuntimeProvider(
        MODELS,
        (ROLE,),
        responder=responder
        or (lambda model_id, role, history, text: "虚构回复：请先核对触发计数与存图数量。"),
    )


def _run(tmp_path, **kwargs):
    cases, _ = _cases()
    defaults = {
        "provider": _provider(),
        "cases": cases,
        "models": [
            ModelPlan("base", True),
            ModelPlan("sft_final", True),
            ModelPlan("cpt_stage1", False, "MODEL_UNAVAILABLE"),
        ],
        "generation": GenerationConfig(max_new_tokens=16, do_sample=True, seed=7),
        "role_id": "CS_AGENT",
        "output_dir": tmp_path / "run",
        "resume": False,
    }
    defaults.update(kwargs)
    return run_evaluation(**defaults)


