def test_d06_reveal_counts_ties_failures_skips(tmp_path):
    result = _run(tmp_path / "run")
    payload = result.to_dict()
    prompts = {r["case_id"]: r["prompt"] for r in payload["records"]}
    pack, private = make_blind_pack(payload["records"], seed=5, prompts=prompts)
    reviews = []
    choices = ["left", "right", "tie", "both_fail", "skip"]
    for index, item in enumerate(pack.items):
        choice = choices[index % len(choices)]
        scores = {DIMENSIONS[0]: 4, DIMENSIONS[3]: 2} if index % 2 == 0 else {}
        record = submit_review(
            pack,
            tmp_path / "reviews",
            item_id=item.item_id,
            choice=choice,
            scores=scores,
            reason=f"fixture {index}",
            reviewer="tester",
        )
        reviews.append(record)
    summary = reveal(pack, private, reviews)
    assert summary.item_count == len(pack.items)
    assert sum(summary.counts.values()) == len(pack.items)
    for choice in choices:
        assert summary.counts[choice] >= 1
    assert summary.dimension_stats[DIMENSIONS[0]]["count"] == sum(
        1 for r in reviews if DIMENSIONS[0] in r.scores
    )
    assert summary.missing[DIMENSIONS[0]] == len(pack.items) - summary.dimension_stats[DIMENSIONS[0]]["count"]
    # Independent case/event counts never exceed the number of reviewed items.
    assert summary.independent_cases <= len(pack.items)
    assert summary.independent_events <= len(pack.items)


