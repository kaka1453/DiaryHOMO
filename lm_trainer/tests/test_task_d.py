def test_d07_report_records_actual_injection_and_rejection(tmp_path):
    fixture, _ = load_card_fixture(CARDS)
    conditions = build_conditions(fixture)
    result = _run(
        tmp_path,
        memory_conditions=("M0", "M1", "M2", "M3", "M4"),
        cards=conditions,
    )
    reasons = {}
    for record in result.records:
        for entry in record.card_audit:
            reasons.setdefault(record.memory_condition, set()).add(entry["reason"])
    assert reasons.get("M0", set()) == set()
    # Task C's Mock backend cannot verify a tokenized prompt, so it downgrades a
    # selected card to ``not_sent``. Both outcomes mean "the card was admitted
    # by the ACL/scope/version gate", which is what D07 needs to prove.
    admitted = {"injected", "not_sent"}
    assert reasons["M1"] & admitted
    assert reasons["M2"] & admitted
    assert reasons["M3"] & admitted
    assert "stale" in reasons["M3"], "the older conflict version must be rejected"
    assert {"namespace", "read_denied", "superseded"} <= reasons["M4"]
    assert reasons["M4"] & admitted
    # Only card ids/versions/reasons are stored; never card plaintext.
    for record in result.records:
        for entry in record.card_audit:
            assert set(entry) == {"card_id", "version", "reason"}


